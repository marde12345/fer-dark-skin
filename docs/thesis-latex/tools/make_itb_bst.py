"""Generate itb-sps.bst from TeX Live's apalike.bst.

Adapts the reference-list format to the "Daftar Pustaka" example in the ITB
Petunjuk Teknis Penulisan Tesis Magister (Juni 2017, p. 12):
  Baker, A. A., Sosro, K., dan Suditomo, B. (1998): Pembakaran hutan di
      Kalimantan, Majalah Kehutanan, 5, 23 - 25.
i.e. authors joined with "dan", "(Year):" after the authors, title followed by a
comma, journal in italics, volume in bold, then the page range; book chapters
use "dalam <editor>, ed., <Book>". In-text citations (natbib author-date,
"(Nama belakang penulis, Tahun)", Juknis p. 10) are unchanged.

Each patch must match exactly once, or the script stops. Run from
docs/thesis-latex/:
    python tools/make_itb_bst.py "$(kpsewhich apalike.bst)"
"""

import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
OUT = Path(__file__).resolve().parents[1] / "itb-sps.bst"

PATCHES = [
    # header (apalike's licence requires a renamed file for modified versions)
    ("% BibTeX `apalike' bibliography style",
     "% itb-sps.bst: ITB SPs reference-list format, generated by tools/make_itb_bst.py\n"
     "% from apalike.bst. Original header follows.\n%\n% BibTeX `apalike' bibliography style"),
    # authors joined with "dan"
    ('{ " and " * t * }', '{ " dan " * t * }'),
    # "(Year):" after the authors; the following title is written without an extra period
    ('" (" year * extra.label * ")" *\n      mid.sentence \'output.state :=',
     '" (" year * extra.label * "): " *\n      before.all \'output.state :='),
    # editors abbreviated "ed."
    ('{ ", editors" * }\n        { ", editor" * }', '{ ", ed." * }\n        { ", ed." * }'),
    # page ranges without the word "pages"
    ('{ "pages" pages n.dashify tie.or.space.connect }\n        { "page" pages tie.or.space.connect }',
     '{ pages n.dashify }\n        { pages }'),
    # volume bold, issue in parentheses, then ", pages"
    ('{ volume field.or.null\n  number empty$\n    \'skip$\n    { "(" number * ")" * *',
     '{ volume empty$\n    { "" }\n    { "{\\bfseries " volume * "}" * }\n  if$\n  number empty$\n    \'skip$\n    { "(" number * ")" * *'),
    ('{ ":" * pages n.dashify * }', '{ ", " * pages n.dashify * }'),
    # book chapters: "dalam <editor>, ed., <Book>"
    ('{ "In " booktitle emphasize * }\n        { "In " format.editors * ", " * booktitle emphasize * }',
     '{ "dalam " booktitle emphasize * }\n        { "dalam " format.editors * ", " * booktitle emphasize * }'),
]

# Entry-type bodies: title followed by a comma (no new.block), and no new.sentence before publisher.
ENTRY_PATCHES = {
    "article": [('format.title "title" output.check\n  new.block\n  crossref missing$',
                 'format.title "title" output.check\n  crossref missing$')],
    "incollection": [('format.title "title" output.check\n  new.block\n  crossref missing$',
                      'format.title "title" output.check\n  crossref missing$'),
                     ('format.chapter.pages output\n      new.sentence\n      publisher',
                      'format.chapter.pages output\n      publisher')],
    "inproceedings": [('format.title "title" output.check\n  new.block\n  crossref missing$',
                       'format.title "title" output.check\n  crossref missing$'),
                      ('{ format.in.ed.booktitle "booktitle" output.check',
                       '{ booktitle emphasize "booktitle" output.check'),
                      ('address output                                    % for apalike\n      new.sentence',
                       'address output')],
}

out = src
for old, new in PATCHES:
    n = out.count(old)
    if n != 1:
        sys.exit(f"patch matched {n} times: {old[:60]!r}")
    out = out.replace(old, new)

for entry, patches in ENTRY_PATCHES.items():
    start = out.index(f"FUNCTION {{{entry}}}")
    end = out.index("FUNCTION {", start + 10)
    body = out[start:end]
    for old, new in patches:
        if body.count(old) != 1:
            sys.exit(f"{entry}: patch matched {body.count(old)} times: {old[:60]!r}")
        body = body.replace(old, new)
    out = out[:start] + body + out[end:]

OUT.write_text(out)
print(f"wrote {OUT}")
